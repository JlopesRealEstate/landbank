create schema if not exists private;
create or replace function private.has_role(_role text)
returns boolean language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.user_roles where user_id=(select auth.uid()) and role=_role);
$$;
create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path = '' as $$ select private.has_role('admin'); $$;
revoke all on function public.has_role(text) from public, anon, authenticated;
revoke all on function public.is_admin() from public, anon, authenticated;
grant usage on schema private to authenticated;
grant execute on function private.has_role(text) to authenticated;
grant execute on function private.is_admin() to authenticated;

