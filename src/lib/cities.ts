/** Potencial de consumo anual = população × renda média mensal × 12. */
export const withConsumption = <T extends { population2022: number; avgIncome: number; consumptionPotential: number }>(city: T): T => ({
  ...city,
  consumptionPotential: city.consumptionPotential > 0 ? city.consumptionPotential : city.population2022 * city.avgIncome * 12,
});

export const CITY_BY_SLUG = new Map(CITY_SEED.map((city) => [city.slug, city]));

export function slugifyCity(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

export function findCity(value: string | null | undefined): CitySeed | undefined {
  if (!value) return undefined;
  const slug = slugifyCity(value);
  return (
    CITY_BY_SLUG.get(slug) ??
    CITY_SEED.find((city) => slugifyCity(city.name) === slug) ??
    CITY_SEED.find((city) => slug.includes(slugifyCity(city.name)) && slug.length > 2) ??
    CITY_SEED.find((city) => slugifyCity(city.name).includes(slug) && slug.length > 3)
  );
}

